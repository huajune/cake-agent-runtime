CREATE TABLE public.system_config (key text PRIMARY KEY, value jsonb);
CREATE TABLE public.message_processing_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id text UNIQUE NOT NULL, chat_id text NOT NULL, received_at timestamptz NOT NULL,
  status text NOT NULL DEFAULT 'success', agent_invocation jsonb, batch_id text, tool_calls jsonb,
  agent_steps jsonb, tenant_id uuid
);
CREATE TABLE public.message_processing_invocations (
  message_id text PRIMARY KEY REFERENCES public.message_processing_records(message_id) ON DELETE CASCADE,
  agent_invocation jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
